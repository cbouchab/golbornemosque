#!/usr/bin/env node
/*
 * Turns the mosque's own prayer timetables (the times its TV screens show)
 * into data/mosque-times.js, which the website reads.
 *
 *   node scripts/import-timetables.mjs
 *
 * Reads every timetables/year<YYYY>data.csv: one row per day with the columns
 *   date, fajr, fajr_jamat, sunrise, dhuhr, dhuhr_jamat, asr, asr_2, asr_jamat,
 *   magrib, magrib_jamat, isha, isha_jamat, city, timestamp
 * (asr is the standard Asr the jamaat follows; asr_2, the Hanafi Asr, isn't used).
 *
 * Every file is checked first: each year complete from 1 January to 31
 * December, every time written HH:MM, and the prayers in their proper order.
 * If anything is wrong, nothing is written and the script says what.
 *
 * Needs Node.js 18 or newer. No packages to install.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IN = path.join(ROOT, "timetables");
const OUT = path.join(ROOT, "data", "mosque-times.js");

// The website's names for each column, in the order every day is written.
const FIELDS = [
  ["fajr", "fajr"],
  ["fajrIqamah", "fajr_jamat"],
  ["sunrise", "sunrise"],
  ["dhuhr", "dhuhr"],
  ["dhuhrIqamah", "dhuhr_jamat"],
  ["asr", "asr"],
  ["asrIqamah", "asr_jamat"],
  ["maghrib", "magrib"],
  ["maghribIqamah", "magrib_jamat"],
  ["isha", "isha"],
  ["ishaIqamah", "isha_jamat"],
];
// Start times must run in this order through the day.
const ORDER = ["fajr", "sunrise", "dhuhr", "asr", "magrib", "isha"];

const problems = [];
const minutes = (t) => Number(t.slice(0, 2)) * 60 + Number(t.slice(3));
const iso = (date) => date.toISOString().slice(0, 10);

// A simple CSV reader: these files have no quoted fields.
function parse(text, file) {
  const lines = text.replace(/^﻿/, "").split(/\r?\n/).filter((l) => l.trim());
  const header = lines[0].split(",").map((h) => h.trim());
  for (const [, col] of FIELDS) if (!header.includes(col)) problems.push(`${file}: no "${col}" column`);
  if (!header.includes("date")) problems.push(`${file}: no "date" column`);
  return lines.slice(1).map((line) => Object.fromEntries(line.split(",").map((v, i) => [header[i], v.trim()])));
}

const files = (await readdir(IN)).filter((f) => /^year\d{4}data\.csv$/i.test(f)).sort();
if (!files.length) {
  console.error(`✗ No timetable files found in timetables/ (expected names like year2026data.csv).`);
  process.exit(1);
}

const years = {};
let updated = "";
for (const file of files) {
  const year = Number(file.match(/\d{4}/)[0]);
  const rows = parse(await readFile(path.join(IN, file), "utf8"), file);
  const days = [];
  const first = new Date(Date.UTC(year, 0, 1));
  const length = (Date.UTC(year + 1, 0, 1) - first) / 86400000;

  rows.forEach((row, i) => {
    const expected = iso(new Date(first.getTime() + i * 86400000));
    if (row.date !== expected) {
      problems.push(`${file}, row ${i + 2}: date ${row.date}, expected ${expected}`);
      return;
    }
    for (const [, col] of FIELDS) {
      if (!/^\d{2}:\d{2}$/.test(row[col] || "") || minutes(row[col]) >= 24 * 60) problems.push(`${file}, ${row.date}: ${col} is "${row[col]}"`);
    }
    for (let k = 1; k < ORDER.length; k++) {
      if (minutes(row[ORDER[k]]) <= minutes(row[ORDER[k - 1]])) problems.push(`${file}, ${row.date}: ${ORDER[k]} is not after ${ORDER[k - 1]}`);
    }
    if (row.timestamp && row.timestamp.slice(0, 10) > updated) updated = row.timestamp.slice(0, 10);
    days.push(FIELDS.map(([, col]) => (row[col] || "").replace(":", "")).join(""));
  });
  if (rows.length !== length) problems.push(`${file}: ${rows.length} days, expected ${length}`);
  years[year] = days;
}

if (problems.length) {
  console.error(`✗ data/mosque-times.js was not changed. Please check the timetable files:`);
  for (const p of problems.slice(0, 20)) console.error(`  - ${p}`);
  if (problems.length > 20) console.error(`  …and ${problems.length - 20} more.`);
  process.exit(1);
}

const body = Object.entries(years)
  .map(([year, days]) => `    "${year}": ${JSON.stringify(days)}`)
  .join(",\n");
const file =
  `/*\n` +
  ` * Golborne Mosque — the mosque's own prayer timetable: the times its screens show.\n` +
  ` * Generated by scripts/import-timetables.mjs from the files in timetables/\n` +
  ` * (see README → Prayer times). Do not edit by hand.\n` +
  ` *\n` +
  ` * Each year lists its days from 1 January. A day is its eleven times as HHMM,\n` +
  ` * run together in the order of \`fields\`.\n` +
  ` */\n` +
  `window.MOSQUE_TIMES = {\n` +
  `  "updated": ${JSON.stringify(updated || null)},\n` +
  `  "fields": ${JSON.stringify(FIELDS.map(([name]) => name))},\n` +
  `  "years": {\n${body}\n  }\n` +
  `};\n`;
await writeFile(OUT, file);

const list = Object.keys(years);
const total = Object.values(years).reduce((n, d) => n + d.length, 0);
console.log(`✓ Saved ${total} days (${list[0]}–${list[list.length - 1]}) to data/mosque-times.js, ${Math.round(file.length / 1024)} KB.`);
